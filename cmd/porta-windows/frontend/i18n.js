export function initialLanguage() {
  try {
    const saved = localStorage.getItem("porta.language");
    if (saved === "en" || saved === "zh-CN") return saved;
  } catch (_) {}
  return navigator.languages?.some((value) => value.toLowerCase().startsWith("zh")) ? "zh-CN" : "en";
}

export function translate(language, message, values = {}) {
  if (language === "zh-CN" && message.startsWith("invalid server URL:")) {
    return chinese["Enter a valid HTTPS gateway URL."];
  }
  let result = language === "zh-CN" ? chinese[message] || message : message;
  for (const [name, value] of Object.entries(values)) {
    result = result.split(`{${name}}`).join(String(value));
  }
  return result;
}
